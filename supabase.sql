-- Art by 21 live booking database
create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  barber text not null check (barber in ('Toma', 'Albert')),
  booking_date date not null,
  booking_time time not null check (booking_time in ('15:00:00','17:00:00','19:00:00','21:00:00')),
  client_name text not null,
  contact text not null,
  service text not null,
  notes text,
  created_at timestamptz not null default now(),
  unique (barber, booking_date, booking_time)
);

alter table public.bookings enable row level security;

-- Public website can read occupied slots.
create policy "public can read bookings"
on public.bookings for select
to anon
using (true);

-- Public website can create bookings.
create policy "public can create bookings"
on public.bookings for insert
to anon
with check (true);

create index if not exists bookings_lookup_idx
on public.bookings (barber, booking_date, booking_time);
